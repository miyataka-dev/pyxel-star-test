# にゃんこジェット (Nyanko Jet) — Pyxel port
#
# A faithful port of the JS/Excalibur version (~/workspace/games/nyanko-jet/,
# src/game.js) to Pyxel (Python). The cat walks on the Earth strip at the
# bottom of the 128x128 screen and fires koban from alternating paws at
# alien formations descending toward Earth.
#
# Timing model mirrors the JS version exactly: pyxel.init(fps=30), one
# update() = one fixed 1/30 s logic step; speeds are px/s integrated with
# dt = 1/30; logical positions are floats, drawn positions are rounded to
# whole pixels (jr() = JS Math.round). Animation timing follows the .ase
# durations (66/33/66/33 ms shooting, 200 ms UFO, 66 ms bullet/bomb) via
# an ms accumulator (anim_advance), exactly like the JS animAdvance.
#
# Art: the user's own pixel art (upload-3.ase / upload-5.ase exports,
# indexed PICO-8 palette). Images/sounds/music normally load from
# nyanko_jet.pyxres (built by tools/build_pyxres.py). If that file cannot
# be loaded (e.g. a host carrying only this .py), the game rebuilds the
# same resources at startup from embedded pixel data + the programmatic
# audio builders below, so the single file stays runnable.
#
# Verification state lives on the App instance as flat attributes
# (steps, player_x, shots_fired, score, aliens_landed, cat_hits,
# enemy_shots_fired, aliens, enemy_bullets, wave_pattern, wave_state,
# phase, sfx_* counters, bgm_playing, ...), mirroring the JS __state.
#
# Test hooks (counterparts of the JS __test* hooks), read from the
# environment at startup:
#   NYANKO_ENEMY_DELAY=<steps>  override the 200-step first-wave delay
#   NYANKO_START_PATTERN=<1-5>  start that wave pattern on the first step

