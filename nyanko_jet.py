_NOTE_CHARS = ["c", "c#", "d", "d#", "e", "f", "f#", "g", "g#", "a", "a#", "b"]


def _nname(n):
    """Pyxel note number -> note-name string for Sound.set."""
    return _NOTE_CHARS[n % 12] + str(n // 12)


def _set_sound(idx, notes, tones, vols, fx, speed):
    pyxel.sounds[idx].set(
        "".join("r" if n is None else _nname(n) for n in notes),
        "".join(tones),
        "".join(str(v) for v in vols),
        "".join(fx),
        speed,
    )


def _build_sfx():
    """The five jsfxr sounds approximated as Pyxel sounds.

    Characters preserved from the JS measurements: shoot = tiny square
    blip ~1550 Hz dropping; explosion = square arpeggio scattering
    ~1030 Hz down to ~290-370 Hz (NOT noise), ~0.36 s; hit = thin
    (pulse) square ~990 Hz dropping; landed = square two-step arpeggio
    ~455 -> ~170 Hz; enemyshot = descending square ~1130 -> ~650 Hz.
    Onset volumes follow the user's approved post-master peak balance
    (shoot .077 / explosion .145 / hit .181 / landed .194 /
    enemyshot .150) scaled onto Pyxel's 0-7 volume range.
    SFX speed 3 = 0.025 s per note slot.
    """
    # shoot: 0.10 s square blip, 1568 -> 880 Hz
    _set_sound(SND_SHOOT, [55, 52, 49, 45], "ssss",
               [3, 2, 2, 1], "nsss", 3)
    # explosion: 0.375 s square arpeggio scatter, 1046 -> 370 Hz
    _set_sound(SND_EXPLOSION,
               [48, 36, 46, 34, 44, 33, 42, 31, 40, 29, 38, 28, 35, 29, 30],
               "s" * 15,
               [5, 5, 4, 4, 4, 3, 3, 3, 3, 2, 2, 2, 2, 1, 1],
               "n" * 15, 3)
    # hit: 0.125 s thin pulse, 988 -> 494 Hz
    _set_sound(SND_HIT, [47, 44, 41, 38, 34], "ppppp",
               [6, 5, 4, 3, 2], "nssss", 3)
    # landed: 0.125 s square two-step arp, 466 -> 175 Hz
    _set_sound(SND_LANDED, [34, 34, 26, 17, 17], "sssss",
               [7, 6, 5, 4, 3], "nnnnn", 3)
    # enemyshot: 0.10 s square descent, 1109 -> 659 Hz
    _set_sound(SND_ENEMYSHOT, [48, 45, 42, 40], "ssss",
               [5, 4, 3, 2], "nsss", 3)


# --- BGM: "NEON GROOVE" (bgmhou-bu candidate 3), tables verbatim ---------
# All phrase/pattern strings below are the bgmhou-bu source text verbatim,
# exactly as ported into the JS version's BGM_TRACK_C (including the '>'
# pitch-bend and '~' glide notation). Do not re-space or re-voice them.
# Structure: INTRO 4 bars + MAIN 16 bars = one 20-bar loop. Bar rule:
# bars 0-3 use introRoots/introRiff; main bar mb (0-based) uses roots[mb]
# with riff[mb % 4], or riffVar[mb % 4] when mb >= 12. The final bar adds
# a snare fill at steps 8, 10, 12, 13, 14, 15 (vel 0.3 + i * 0.11).

_REST16 = ". . . . . . . . . . . . . . . ."
_DOTS16 = "................"

BGM_ROOTS = ["E1", "E1", "E1", "E1", "G1", "G1", "A1", "A1",
             "E1", "E1", "E1", "E1", "C2", "D2", "E1", "E1"]
BGM_INTRO_ROOTS = ["E1", "E1", "E1", "E1"]
BGM_RIFF = [
    "0:2 . . 0 . . 12 . . 0 . 10 . . 7",
    "0:2 . . ~12 . 0 . . 10 . 0 . 12>10:2 .",
    "0 . . 0:2 . 12 . . 0 . 14 . 12 . 10",
    "0:3 . 7 . . 10 . 12 . . 0 . 5>7:2",
]
BGM_RIFF_VAR = [
    "0:2 . 12 . . 0 . 15 . 12 . 0 . 10 .",
    "0 . . ~7 . 0 . . 12 . 10>12:2 . 0 . .",
    "0 12 . 0:2 . . 10 . 12 . 0 . 14 . .",
    "0:4 . . 12 . 0 . 10 . 7 . 12>19:2",
]
BGM_INTRO_RIFF = [
    _REST16,
    "0:6 . . . . . . . . . .",
    "0:2 . . 0 . . 12 . . 0 . 10 . . 7",
    "0:2 . . 0 . . 12 . . 0 . 12>14:2 . .",
]
BGM_PERC_INTRO = [
    {"kick": _DOTS16, "snare": "....x.......x...", "hat": _DOTS16,
     "open": _DOTS16},
    {"kick": "x...............", "snare": "....x.......x...",
     "hat": "x..x..x.x..x..x.", "open": _DOTS16},
    {"kick": "x......x..x.....", "snare": "....x.......x..g",
     "hat": "x..x..x.x..x..x.", "open": "....o..........."},
    {"kick": "x......x..x.....", "snare": "....x.......x..g",
     "hat": "x..x..x.x..x..x.", "open": "o..............."},
]
BGM_PERC_MAIN = {"kick": "x......x..x.....", "snare": "....x.......x..g",
                 "hat": "x..x..x.x..x..x.", "open": "....o.......o..."}


def _root_pyxel_note(name):
    """Note name ('E1') -> Pyxel note number (JS bgmNoteMidi - 12)."""
    semis = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
    midi = (int(name[1:]) + 1) * 12 + semis[name[0]]
    return midi - 12


def _parse_riff(s):
    """Phrase parser, ported from bgmhou-bu parseRiff (via game.js).

    '.' = rest (1 step), 'n' = +n semitones from the bar root,
    'n:len' = length len steps (default 1), 'a>b:len' = pitch bend,
    '~n' = glide from the previous note's final pitch.
    """
    notes = []
    step = 0
    for tok in s.split():
        if tok == ".":
            step += 1
            continue
        m = re.match(r"^(~?)(-?\d+)(?:>(-?\d+))?(?::(\d+))?$", tok)
        if not m:
            step += 1
            continue
        length = int(m.group(4)) if m.group(4) else 1
        notes.append({
            "step": step,
            "offset": int(m.group(2)),
            "len": length,
            "glide": m.group(1) == "~",
            "bend_to": int(m.group(3)) if m.group(3) is not None else None,
        })
        step += length
    return notes


def _build_bars():
    """Per-bar events for all 20 bars, mirroring the JS BGM_BARS build.

    Returns a list of (bass, perc): bass[step] is None or
    (pyxel_note, len, glide, bend_pyxel_note_or_None, velocity);
    perc[step] is a list of (instrument, velocity).
    Velocities follow bgmhou-bu buildEvents exactly: bass
    (step % 4 == 0) ? 0.95 : 0.78; hat by step position 0.5/0.38/0.27;
    snare 'x' 0.85 / ghost 'g' 0.32; kick 0.9; open 0.55.
    """
    bars = []
    for bar in range(20):
        if bar < 4:
            root = _root_pyxel_note(BGM_INTRO_ROOTS[bar])
            phrase = BGM_INTRO_RIFF[bar]
            pattern = BGM_PERC_INTRO[bar]
        else:
            mb = bar - 4
            root = _root_pyxel_note(BGM_ROOTS[mb])
            phrase = (BGM_RIFF_VAR if mb >= 12 else BGM_RIFF)[mb % 4]
            pattern = BGM_PERC_MAIN
        bass = [None] * 16
        for n in _parse_riff(phrase):
            vel = 0.95 if n["step"] % 4 == 0 else 0.78
            bass[n["step"]] = (
                root + n["offset"],
                n["len"],
                n["glide"],
                (root + n["bend_to"]) if n["bend_to"] is not None else None,
                vel,
            )
        perc = [[] for _ in range(16)]
        for inst in ("kick", "snare", "hat", "open"):
            s = pattern[inst]
            for st in range(16):
                ch = s[st]
                if ch == ".":
                    continue
                if inst == "hat":
                    vel = 0.5 if st % 4 == 0 else (0.38 if st % 2 == 0 else 0.27)
                elif inst == "snare":
                    vel = 0.32 if ch == "g" else 0.85
                elif inst == "kick":
                    vel = 0.9
                else:  # open
                    vel = 0.55
                perc[st].append((inst, vel))
        if bar == 19:  # final bar: snare fill on top of the pattern
            for i, fs in enumerate([8, 10, 12, 13, 14, 15]):
                perc[fs].append(("snare", 0.3 + i * 0.11))
        bars.append((bass, perc))
    return bars


def _bass_sound(bass):
    """One bar of bass events -> Pyxel sound slots (16 steps).

    The JS bass is a monophonic voice whose envelope retriggers per
    note; a note of len L occupies L slots: the onset slot carries the
    attack volume, sustain slots use Pyxel's slide effect at ~55%
    volume (the JS sustain level) so the pitch holds without a fresh
    attack. A glide note ('~') slides into its first slot; a bend note
    ('a>b') slides to the bend target on its last slot. The JS sawtooth
    main oscillator has no Pyxel counterpart; square is used (the JS
    sub-oscillator is muted in the current JS build, BGM_SUB_GAIN=0,
    so only the main line is ported).
    """
    notes = [None] * 16
    vols = [0] * 16
    fx = ["n"] * 16
    for step, ev in enumerate(bass):
        if ev is None:
            continue
        pitch, length, glide, bend, vel = ev
        v_on = 7 if vel > 0.9 else 5
        v_sus = 4 if vel > 0.9 else 3
        notes[step] = pitch
        vols[step] = v_on
        fx[step] = "s" if glide else "n"
        for k in range(1, length):
            s2 = step + k
            if s2 >= 16:
                break
            if bend is not None and k == length - 1:
                notes[s2] = bend
            else:
                notes[s2] = pitch
            vols[s2] = v_sus
            fx[s2] = "s"
    return notes, vols, fx


# One Pyxel channel plays one note per step, so simultaneous percussion
# hits in the JS pattern collide; priority: kick > snare > open > hat.
_PERC_PRIO = {"hat": 0, "open": 1, "snare": 2, "kick": 3}


def _perc_sound(perc):
    """One bar of percussion events -> Pyxel sound slots (16 steps).

    Noise tone stands in for the JS LFSR percussion: hat/snare/open are
    noise bursts (fadeout effect for the short ones). The kick — a
    short-period LFSR buzz through a 420 Hz lowpass in the JS — becomes
    a low triangle thump with fadeout.
    """
    notes = [None] * 16
    tones = ["n"] * 16
    vols = [0] * 16
    fx = ["n"] * 16
    for step, hits in enumerate(perc):
        if not hits:
            continue
        inst, vel = max(hits, key=lambda h: _PERC_PRIO[h[0]])
        vols[step] = int(vel * 7 + 0.5)
        if inst == "kick":
            notes[step] = 12  # ~131 Hz triangle thump
            tones[step] = "t"
            fx[step] = "f"
        elif inst == "snare":
            notes[step] = 33
            tones[step] = "n"
            fx[step] = "f"
        elif inst == "open":
            notes[step] = 33
            tones[step] = "n"
            fx[step] = "n"
        else:  # hat
            notes[step] = 33
            tones[step] = "n"
            fx[step] = "f"
    return notes, tones, vols, fx


def build_audio():
    """Set all SFX sounds, BGM bar sounds and music 0 on the live banks."""
    _build_sfx()
    for i, (bass, perc) in enumerate(_build_bars()):
        notes, vols, fx = _bass_sound(bass)
        _set_sound(SND_BASS_BAR0 + i, notes, ["s"] * 16, vols, fx, BGM_SPEED)
        notes, tones, vols, fx = _perc_sound(perc)
        _set_sound(SND_PERC_BAR0 + i, notes, tones, vols, fx, BGM_SPEED)
    pyxel.musics[MUSIC_BGM].set(
        [SND_BASS_BAR0 + i for i in range(20)],
        [SND_PERC_BAR0 + i for i in range(20)],
        [],
        [],
    )


# ---------------------------------------------------------------------------
# Enemy movement paths (ported from game.js).
# Each move function sets the enemy's logical center (e.lx, e.ly) from
# t = the enemy's age in seconds of step time (pattern 3 uses the shared
# formation age). A path may set e.exited = True when the enemy leaves
# the screen legitimately (U-turn climb-out, circle rise-out); exited
# enemies are removed WITHOUT counting as landed. Reaching the ground
# (bottom edge >= GROUND_Y) is handled generically as landed.
# ---------------------------------------------------------------------------


def move_plain(e, t, app):
    """Plain descender (kept for parity with the JS test alien)."""
    e.lx = e.p["x0"]
    e.ly = e.p["y0"] + ALIEN_SPEED * t


def move_uturn(e, t, app):
    """Pattern 1: descend at 24 px/s to y=64, half-circle of radius 12
    toward the center (x shifts by 24), climb back up and exit."""
    desc_t = (64 - 4) / ALIEN_SPEED  # 2.5 s
    turn_t = math.pi / 2             # semicircle at omega = 2 rad/s
    if t < desc_t:
        e.lx = e.p["x0"]
        e.ly = 4 + ALIEN_SPEED * t
    elif t < desc_t + turn_t:
        tau = t - desc_t
        th = (math.pi if e.p["dir"] > 0 else 0) - e.p["dir"] * 2 * tau
        e.lx = (e.p["x0"] + e.p["dir"] * 12) + 12 * math.cos(th)
        e.ly = 64 + 12 * math.sin(th)
    else:
        e.lx = e.p["x0"] + e.p["dir"] * 24
        e.ly = 64 - ALIEN_SPEED * (t - desc_t - turn_t)
        if e.ly <= -4:
            e.exited = True


def move_zigzag(e, t, app):
    """Pattern 2: enter from one side edge at y=16, triangle-wave x at
    42 px/s (entry edge to x=100 on that side and back) while
    descending at 18 px/s."""
    span = 108  # from entry x=-8 to x=100 (mirrored for right entry)
    d = (42 * t) % (2 * span)
    off = d if d < span else 2 * span - d
    entry_x = -8 + off
    e.lx = entry_x if e.p["dir"] > 0 else SCREEN_W - entry_x
    e.ly = 16 + 18 * t


def move_circle(e, t, app):
    """Pattern 3: circle of radius 16 around a center descending at
    14 px/s from y=-20 to y=88, then rising back out; the formation
    rotates at 90 deg/s. t is the shared formation age."""
    desc_t = 108 / 14  # (88 - -20) / 14 = 7.714 s
    cy = -20 + 14 * t if t < desc_t else 88 - 14 * (t - desc_t)
    th = math.radians(e.p["slot"] * 60 + 90 * t)
    e.lx = 64 + 16 * math.cos(th)
    e.ly = cy + 16 * math.sin(th)
    if t > desc_t and e.ly <= -4:
        e.exited = True


def move_merge(e, t, app):
    """Pattern 4: x eases (easeInOutCubic) from the entry corner to
    the center column x=64 over 2 s while y descends at 20 px/s."""
    e.ly = 4 + 20 * t
    e.lx = (e.p["x0"] + (64 - e.p["x0"]) * ease_in_out_cubic(t / 2.0)
            if t < 2.0 else 64)


def move_dive(e, t, app):
    """Pattern 5: hold along the top (y=12) until the dive age, lock
    onto the cat's x at that moment, dive at 55 px/s along the locked
    direction until crashing into the ground line (counted landed)."""
    if e.dive is None:
        e.lx = e.p["slot_x"]
        e.ly = 12
        if t >= e.p["dive_age"]:
            dx = app.p_lx - e.lx
            dy = GROUND_Y - e.ly
            ln = math.hypot(dx, dy) or 1
            e.dive = (e.lx, e.ly, t, 55 * dx / ln, 55 * dy / ln)
    else:
        fx, fy, t0, vx, vy = e.dive
        d = t - t0
        e.lx = fx + vx * d
        e.ly = fy + vy * d


