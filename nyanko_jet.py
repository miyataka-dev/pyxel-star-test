class Star:
    """One background star drifting downward, wrapping at the ground."""

    def __init__(self, x, y, speed, size, color):
        self.x = x
        self.ly = y
        self.speed = speed
        self.size = size
        self.color = color

    def step(self):
        self.ly += self.speed * STEP
        if self.ly >= GROUND_Y:
            self.ly -= GROUND_Y


class Koban:
    """Player bullet: 5x8, flies straight up at 170 px/s."""

    def __init__(self, cx, cy):
        self.lx = float(cx)  # logical float CENTER position
        self.ly = float(cy)
        self.dead = False

    def step(self):
        self.ly -= BULLET_SPEED * STEP
        if self.ly < -4:
            self.dead = True


class EnemyBullet:
    """8x8 spinning capsule (4-frame loop at 66 ms). A vector bullet:
    velocity (vx, vy) with |v| = 60 px/s. Removed when its bottom edge
    reaches the ground line, on side/top exit, or on hitting the cat."""

    def __init__(self, cx, cy, vx, vy):
        self.lx = float(cx)  # logical float CENTER position
        self.ly = float(cy)
        self.vx = vx
        self.vy = vy
        self.anim = [0.0, 0, False]
        self.dead = False

    def step(self):
        self.lx += self.vx * STEP
        self.ly += self.vy * STEP
        anim_advance(self.anim, EBULLET_DURS, STEP_MS, True)
        if (self.ly + 4 >= GROUND_Y or self.lx < -4
                or self.lx > SCREEN_W + 4 or self.ly < -4):
            self.dead = True


class Explosion:
    """Bomb animation at a fixed position: 3 frames at 66 ms, once."""

    def __init__(self, cx, cy):
        self.lx = float(cx)
        self.ly = float(cy)
        self.anim = [0.0, 0, False]
        self.dead = False

    def step(self):
        anim_advance(self.anim, EXPLOSION_DURS, STEP_MS, False)
        if self.anim[2]:
            self.dead = True


class Alien:
    """UFO, 16x8, 2-frame loop at 200 ms. Movement is a path function
    of age; firing is per-pattern ('aimed' | 'down' | 'random'), one
    shot every 1.6-2.6 s (randomized per alien), spawned at the
    alien's bottom center. An optional can_fire gate can hold fire
    (the dive pattern fires only while hovering)."""

    def __init__(self, x, y, move, p, fire_mode, use_form_age=False,
                 can_fire=None, is_wave=False, wave_id=0):
        self.lx = float(x)  # logical float CENTER position
        self.ly = float(y)
        self.move = move
        self.p = p
        self.fire_mode = fire_mode
        self.use_form_age = use_form_age
        self.can_fire = can_fire
        self.is_wave = is_wave
        self.wave_id = wave_id
        self.age = 0.0          # own age in seconds of step time
        self.dive = None        # dive-pattern locked trajectory
        self.exited = False     # left the screen legitimately
        self.anim = [0.0, 0, False]
        self.fire_t = ALIEN_FIRE_MIN + pyxel.rndf(0, ALIEN_FIRE_RAND)
        self.dead = False
        self.landed = False

    def step(self, app):
        self.age += STEP
        t = self.age
        if self.use_form_age and app.wave is not None:
            t = (app.steps - app.wave["start_step"]) * STEP
        self.move(self, t, app)
        anim_advance(self.anim, ENEMY_DURS, STEP_MS, True)
        if self.exited:
            self.dead = True
            return
        if self.ly + 4 >= GROUND_Y:
            self.dead = True
            self.landed = True
            return
        if self.fire_mode != "none" and (
                self.can_fire is None or self.can_fire(self)):
            self.fire_t -= STEP
            if self.fire_t <= 0:
                self.fire_t = ALIEN_FIRE_MIN + pyxel.rndf(0, ALIEN_FIRE_RAND)
                self._fire(app)

    def _fire(self, app):
        if self.fire_mode == "aimed":
            dx = app.p_lx - self.lx
            dy = PLAYER_Y - self.ly
            ln = math.hypot(dx, dy) or 1
            vx = EBULLET_SPEED * dx / ln
            vy = EBULLET_SPEED * dy / ln
        elif self.fire_mode == "random":
            # Random direction inside a downward cone of +/-50 deg.
            phi = math.radians(pyxel.rndf(0, 100) - 50)
            vx = EBULLET_SPEED * math.sin(phi)
            vy = EBULLET_SPEED * math.cos(phi)
        else:  # 'down'
            vx, vy = 0.0, float(EBULLET_SPEED)
        app.enemy_shots_fired += 1
        app.play_sfx("enemyshot")
        app.ebullet_list.append(EnemyBullet(self.lx, self.ly + 4, vx, vy))


