def jr(v):
    """Round like JS Math.round (half up) for drawn positions."""
    return math.floor(v + 0.5)


def clamp(v, lo, hi):
    return lo if v < lo else (hi if v > hi else v)


def ease_in_out_cubic(u):
    return 4 * u * u * u if u < 0.5 else 1 - pow(-2 * u + 2, 3) / 2


def anim_advance(anim, durs, dt_ms, loop):
    """Step-time animation clock, ported from the JS animAdvance.

    anim = [t_ms, frame, done]. Adds dt_ms and advances frames while the
    accumulated time passes each frame's .ase duration. Returns True if
    the frame changed this step.
    """
    if anim[2]:
        return False
    before = anim[1]
    anim[0] += dt_ms
    while anim[0] >= durs[anim[1]]:
        anim[0] -= durs[anim[1]]
        if anim[1] == len(durs) - 1:
            if loop:
                anim[1] = 0
            else:
                anim[2] = True
                break
        else:
            anim[1] += 1
    return anim[1] != before


