# ---------------------------------------------------------------------------
# Audio: SFX + BGM, built programmatically.
#
# The same builders fill the .pyxres (tools/build_pyxres.py) and serve as
# the runtime fallback when the .pyxres is absent.
#
# Sound slots: 0-4 = SFX, 8-27 = BGM bass (one sound per bar, 20 bars),
# 32-51 = BGM percussion (one sound per bar). Music 0 = the BGM loop:
# ch0 = bass bars, ch1 = percussion bars, ch2/ch3 unused by the music so
# SFX can play there (shoot/enemyshot on ch2, explosion/hit/landed on
# ch3). Replaying a sound on its channel restarts it, which preserves
# the JS per-type monophony within each type.
#
# Pyxel note numbers: freq = 440 * 2**((n - 33) / 12), n in 0..59.
# Pyxel sound speed: one note lasts speed/120 s. A 16th note at the
# original 144 BPM lasts 12.5 ticks — not an integer — so the BGM uses
# speed 12 (one note = 1/12 s), i.e. the track runs at 150 BPM (+4.2%).
# The JS swing (0.18) has no Pyxel counterpart and is omitted.
# ---------------------------------------------------------------------------

